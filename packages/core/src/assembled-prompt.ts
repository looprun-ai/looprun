/**
 * @looprun-ai/core — the DOMAIN-NEUTRAL assembled prompt renderer + the `DomainContract` interface (framework-free).
 *
 * This file contains ZERO business content — it is pure assembly machinery. Every business string
 * comes from a GENERATED artifact with exactly one owner: the AgentSpec (persona / Flow / rule sections /
 * Governance / Behavior — per-agent) or the host-injected `DomainContract` (voice / core invariants /
 * language / state-render mapping — common to a business's agents). The per-agent persona (role line,
 * persona-on-spec law) lives on `spec.persona` and renders as the FIRST Behavior bullet; the shared
 * business `voice` lives on the domain and opens the assembled prompt — byte-identical across the domain's agents
 * (shared-prefix law: maximal shared prefix, per-agent divergence as late as possible).
 *
 * State-in-tail: `renderAssembledPrompt` renders ONLY case-invariant content, so the assembled
 * system prompt is BYTE-STABLE across cases/turns of an agent (→ cacheable prefix). The volatile
 * account/brand STATE (`domain.stateBlock`) is NOT rendered here — the runtime rides it on the USER
 * MESSAGE tail (like upload labels), keeping the stable prefix intact. For that to hold, a spec's
 * `persona` MUST be case-invariant (do not interpolate volatile world state into it).
 *
 * PROVENANCE The renderer does not build strings and join them. It builds a typed,
 * attributed table — {@link PromptBlock}[] of {@link PromptRow}s of {@link PromptLine}s — and the assembled prompt
 * string is a pure FOLD over that table ({@link foldPrompt}). A bare `parts.join('\n\n')` is the
 * point where every trace of who-said-what dies, which is precisely why contradictions between
 * sections (and between the assembled prompt and the tool schemas the model also reads) would be structurally
 * unaskable. See `prompt-fold.ts` for the table's shape and the fold that renders it.
 */
