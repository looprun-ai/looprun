export type { SubjectRule, PromptBlock, PromptLine, PromptRow } from './prompt-fold.js';

/** A named tool set a {@link ContractGuardBinding} may target. Each installing lane resolves the name
 *  against its own declarations at construction:
 *    · `'writeTools'`        — `contract.writeTools ∩ lane.tools − exempt` (the write surface is
 *                              contract-wide; the lane keeps only what it carries);
 *    · `'destructiveTools'`  — `lane.destructiveTools − exempt` (destructiveness is decided per desk,
 *                              so the set is the INSTALLING lane's own declaration).
 *  A lane whose resolution comes out empty installs nothing. */
export type DeclaredToolSet = 'writeTools' | 'destructiveTools';

/** ONE guard declaration on the domain contract, installed by every lane that carries its target.
 *  The `target` names literal tools or a {@link DeclaredToolSet}; either way it expands to a literal
 *  `string[]` at install time — a `ToolTarget` never carries a set name. `exempt` withdraws names from
 *  a NAMED set only (a literal list simply omits the tool); an exempt name outside the set throws at
 *  construction. `priority` defaults to `agent`; contract bindings install during the spec
 *  constructor, so within a tier they precede every lane-added binding. */
export interface ContractGuardBinding {
  hook: Hook;
  target: string[] | DeclaredToolSet;
  guard: Guard;
  id: string;
  priority?: Priority;
  exempt?: string[];
}

/** The DOMAIN skin: the business-COMMON strings NOT derived from any single AgentSpec. Host-injected
 *  and, at best, GENERATED by the agentspec skill from the business docs. Carries NO
 *  per-agent persona — that lives on `spec.persona` (persona-on-spec law). */
export interface DomainContract {
  /** The business VOICE paragraph — the assembled prompt's opening. BYTE-IDENTICAL across every agent of the
   *  domain (shared-prefix law: shared/static head, per-agent divergence as late as possible) and
   *  case-invariant (no volatile world state — cacheable prefix). */
  voice: string;
  /** The volatile account/brand-state block — rendered by the runtime onto the USER MESSAGE tail. */
  stateBlock(world: AgentWorld): string;
  /** The "## Core rules (NEVER violate)" invariants — DOMAIN-wide and rendered verbatim into every
   *  agent of the domain. Nothing agent-specific belongs here (agent scope lives on `spec.scope`;
   *  per-tool protocol prose is already composed, scoped to the owner, into that tool's own
   *  description by `composeToolDescription`). */
  coreInvariants: string[];
  /** The final "## Output language (ABSOLUTE)" clause. */
  languageClause: string;
  /** Deterministic honest-abstain closure (verified observations only) — an OVERRIDE seam: when present it
   *  replaces the engine's default derive-and-render exhaustion closure, receiving the same evidence
   *  (world, the turn's domain tool names, produced labels, the violation kinds). */
  exhaustionReply?: (world: AgentWorld, okTools: string[], produced: string[], violations: string[]) => string;
  /** The domain's WORDING (and language) for ONE verified claim in the user-facing operation report —
   *  the domain language seam over {@link renderOperationReport}. Given the VERIFIED fields of a claim
   *  ({@link RenderedClaim}: `target`/`outcome`/`amount`, never the agent-authored advisory `op`) and its
   *  resolved core outcome, return the one-liner the user reads. Absent ⇒ the engine's neutral English
   *  default (which renders the claim's `target` and nothing else). */
  renderClaim?: (claim: RenderedClaim, core: CoreOutcome) => string;
  /** The ENGINE's own user-facing sentences — the record closures and the consent question. The engine
   *  puts these on the user's screen itself, so a conversation held in another language declares them
   *  here. Partial: what is not declared falls back per key to the engine's English. Distinct from
   *  {@link renderClaim}, which words one CLAIM; this words what the engine says around them, and the
   *  consent question is the part that has to be readable — the user types its token back. */
  engineText?: Partial<EngineText>;
  /** The domain's WRITE tools — the ones that MUTATE the world (vs pure reads). The honesty cross-check
   *  (`claimIsGrounded` / `claimIsComplete`, auto-installed when this is non-empty) reads it to ground a
   *  `success` claim against an EFFECTED write and to demand every effected write be reported. Same list
   *  `deriveClaimsFromActionHistory` consumes so the exhaustion closure never announces a no-effect simulate as done —
   *  seated HERE so both the write surface and its {@link outcomes} map arrive together on the one domain object. */
  writeTools?: readonly string[];
  /** The contract's TOOL-GUARD declarations — each installed by every lane whose surface carries the
   *  binding's resolved target (see {@link ContractGuardBinding}). The domain-wide write gate is one of
   *  them: a `precondition` bound to `'writeTools'` at priority `changeAllowed`, declared ONCE so no
   *  lane can key on a third of the condition. */
  guards?: ContractGuardBinding[];
  /** The domain OUTCOME vocabulary: every non-core outcome word an agent may declare in a `did` claim MUST
   *  map to a core outcome (e.g. `{ settled: 'success' }`), so the action history cross-check stays
   *  engine-owned and never becomes semantic. Fed to `claimIsGrounded` beside {@link writeTools}. */
  outcomes?: OutcomeMap;
  /** Fields a result may not carry: `'omit'` deletes, `'mask'` keeps a recognizable masked form.
   *  Dot-suffix paths over result keys. The executor is not trusted to hide anything — this filter
   *  runs on our side of the boundary — and HOW FAR it reaches is decided by the seam the tool
   *  executes on:
   *
   *    · the WORLD seam — the filter runs inside the tool's own `execute`, so the value the model
   *      runtime receives is the filtered one, and the record is filtered with it.
   *    · a SELF-EXECUTING tool (native, MCP) — its `execute` returns straight to the model runtime,
   *      which no engine code sits in front of. The filter reaches the action history and therefore
   *      everything composed from it: the operation record, the closure, the judge envelope, the
   *      sealed turn. The model's own view of that one result is the tool's. */
  sensitiveFields?: Record<string, SensitiveMode>;
  /** Free-text fields (dot-suffix over tool argument and result keys) whose CONTENT is
   *  pattern-scrubbed: emails, Luhn-valid card numbers, conservative phone shapes. A field that
   *  legitimately carries contact data is simply not declared — the acceptance is authored and visible.
   *  On ARGUMENTS the reach is the same on every seam: the scrub rewrites the argument object the
   *  executor is about to receive, so the raw value never leaves the process. On RESULTS it follows
   *  {@link sensitiveFields}. */
  scrubTextFields?: string[];
}

